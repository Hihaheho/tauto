//! The committed record of what each backend does with every case it runs.
//!
//! A backend runner reports one status per selected case: `pass`, or a
//! status that says why the case is not yet a pass (`partial`, `todo`,
//! `declined`, `fail`). The record under `cases/coverage/<backend>.tsv` lists
//! them all. A run that differs from the record fails, so a case that drops
//! out of a backend, newly fails, or starts passing is seen in review.
//! `TAUTO_UPDATE_COVERAGE=1` rewrites the record from an unfiltered run.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

pub fn path(cases: &Path, backend: &str) -> PathBuf {
    cases.join("coverage").join(format!("{backend}.tsv"))
}

pub fn status(kind: &str, text: &str) -> String {
    let line = text.lines().find(|l| !l.trim().is_empty()).unwrap_or("");
    let line = without_scratch_dirs(&line.replace('\t', " "));
    let line: String = line.trim().chars().take(160).collect();
    if line.is_empty() {
        kind.to_string()
    } else {
        format!("{kind}: {line}")
    }
}

/// A case's scratch directory is named by the process and a counter, so a
/// status that names a file in it says `<case>` for the directory instead.
/// The Rust backend's work directory sits under a machine's temporary or
/// target directory, so a status that names it says `<work>`.
fn without_scratch_dirs(line: &str) -> String {
    without_work_dirs(&without_case_dirs(line))
}

fn without_work_dirs(line: &str) -> String {
    const WORK: &str = "tauto-rust-backend/work-";
    let mut out = String::new();
    let mut rest = line;
    while let Some(at) = rest.find(WORK) {
        let start = rest[..at]
            .rfind(|c: char| c.is_whitespace() || c == '(' || c == '`' || c == '\'')
            .map_or(0, |i| i + 1);
        out.push_str(&rest[..start]);
        let tail = &rest[at + WORK.len()..];
        let end = tail
            .find(|c: char| !c.is_ascii_digit())
            .unwrap_or(tail.len());
        out.push_str("<work>");
        rest = &tail[end..];
    }
    out.push_str(rest);
    out
}

fn without_case_dirs(line: &str) -> String {
    let dir = std::env::temp_dir().join("tauto-cases-");
    let dir = dir.to_string_lossy();
    let mut out = String::new();
    let mut rest = line;
    while let Some(at) = rest.find(dir.as_ref()) {
        out.push_str(&rest[..at]);
        let tail = &rest[at + dir.len()..];
        let end = tail
            .find(|c: char| !(c.is_ascii_digit() || c == '-'))
            .unwrap_or(tail.len());
        out.push_str("<case>");
        rest = &tail[end..];
    }
    out.push_str(rest);
    out
}

fn read(path: &Path) -> Result<BTreeMap<String, String>, String> {
    let text = match std::fs::read_to_string(path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
        Err(e) => return Err(format!("{}: {e}", path.display())),
    };
    let mut out = BTreeMap::new();
    for line in text
        .lines()
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
    {
        let (case, status) = line
            .split_once('\t')
            .ok_or_else(|| format!("{}: not `case<TAB>status`: {line}", path.display()))?;
        if out.insert(case.to_string(), status.to_string()).is_some() {
            return Err(format!("{}: {case} is listed twice", path.display()));
        }
    }
    Ok(out)
}

fn write(path: &Path, got: &BTreeMap<String, String>) -> Result<(), String> {
    let mut text = String::from(
        "# Generated by the case runners (tools/tauto-test-suite/src/coverage.rs).\n\
         # One line per case: pass, or partial / todo / declined / fail with the reason;\n\
         # see docs/design/test-suite.md.\n",
    );
    for (case, status) in got {
        text.push_str(&format!("{case}\t{status}\n"));
    }
    std::fs::create_dir_all(path.parent().unwrap()).map_err(|e| e.to_string())?;
    std::fs::write(path, text).map_err(|e| e.to_string())
}

/// Compare a run with the record. With no filter and `TAUTO_UPDATE_COVERAGE`
/// set, rewrite the record instead. Returns the differences.
pub fn check(
    cases: &Path,
    backend: &str,
    filter: Option<&str>,
    got: &BTreeMap<String, String>,
) -> Result<Vec<String>, String> {
    let path = path(cases, backend);
    if filter.is_none() && std::env::var_os("TAUTO_UPDATE_COVERAGE").is_some() {
        write(&path, got)?;
        return Ok(Vec::new());
    }
    let want = read(&path)?;
    let mut diffs = Vec::new();
    for (case, status) in &want {
        if filter.is_some_and(|f| !case.contains(f)) {
            continue;
        }
        match got.get(case) {
            None => diffs.push(format!("{case}: recorded as {status:?}, but not run")),
            Some(got) if got != status => {
                diffs.push(format!("{case}: recorded as {status:?}, now {got:?}"))
            }
            Some(_) => {}
        }
    }
    for (case, status) in got {
        if !want.contains_key(case) {
            diffs.push(format!("{case}: not recorded, now {status:?}"));
        }
    }
    Ok(diffs)
}

/// Print a summary and the differences; true when the run matches the record.
pub fn report(
    cases: &Path,
    backend: &str,
    filter: Option<&str>,
    got: &BTreeMap<String, String>,
) -> bool {
    let mut counts = BTreeMap::<&str, usize>::new();
    for status in got.values() {
        *counts.entry(status.split(':').next().unwrap()).or_default() += 1;
    }
    println!("\n{backend}: {counts:?}");
    match check(cases, backend, filter, got) {
        Ok(diffs) if diffs.is_empty() => true,
        Ok(diffs) => {
            println!(
                "\n{} differ from {}:",
                diffs.len(),
                path(cases, backend).display()
            );
            for d in &diffs {
                println!("  {d}");
            }
            println!(
                "rerun with TAUTO_UPDATE_COVERAGE=1 (and no filter) to accept the new statuses"
            );
            false
        }
        Err(e) => {
            println!("{e}");
            false
        }
    }
}

/// Run every case `backend` selects through a runner, print the statuses that
/// are not `pass`, and compare them with the record. True on a match that
/// checked at least one case successfully.
///
/// Cases run on `test_threads()` workers. `make_runner` builds one runner for
/// each worker (given its number), so a runner keeps its own scratch
/// directories and build lanes; the statuses are printed and compared in the
/// order of the case names.
pub fn run_backend<R: FnMut(usize, &crate::RustCase) -> String>(
    cases_dir: &Path,
    backend: crate::Scenario,
    filter: Option<&str>,
    make_runner: impl Fn(usize) -> R + Sync,
) -> Result<bool, String> {
    // The expected messages of the cases are the English ones, whichever
    // cases the filter leaves to run first.
    tauto_messages::install();
    let mut cases = crate::rust_cases(cases_dir)?;
    cases.retain(|case| {
        filter.is_none_or(|f| case.name.contains(f)) && case.selects_backend(backend.name())
    });
    let statuses = crate::parallel_map(&cases, make_runner, |run, i, case| {
        let mut s = run(i, case);
        // An `unimplemented` case is recorded, never a hard failure; it turns
        // into `pass` in the record once the backend runs it.
        if case.unimplemented {
            if let Some(why) = s.strip_prefix("fail") {
                s = format!("todo: unimplemented{why}");
            }
        }
        s
    });
    let mut got = BTreeMap::new();
    for (case, s) in cases.iter().zip(statuses) {
        got.insert(case.name.clone(), s);
    }
    for (name, s) in &got {
        if s != "pass" {
            println!("{} {name}: {s}", backend.name());
        }
    }
    if !got.values().any(|s| s == "pass") {
        println!("{}: no case checked successfully", backend.name());
        return Ok(false);
    }
    Ok(report(cases_dir, backend.name(), filter, &got))
}

#[cfg(test)]
mod tests {
    use super::without_work_dirs;

    #[test]
    fn a_work_directory_is_named_without_its_machine_path() {
        assert_eq!(
            without_work_dirs("the source is in /tmp/tauto-rust-backend/work-0):"),
            "the source is in <work>):"
        );
        assert_eq!(
            without_work_dirs("(/a/b/tauto-rust-backend/work-12/src/main.rs)"),
            "(<work>/src/main.rs)"
        );
    }
}
