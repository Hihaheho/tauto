//! The trusted mutable adapter executes the checked transition on both backends.
use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
};

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}
fn run(path: &Path, native: bool, target: &Path) -> String {
    let mut cmd = Command::new(env!("CARGO_BIN_EXE_tauto"));
    if native {
        cmd.args(["run", "--backend", "rust"]);
    } else {
        cmd.args(["run", "--tote"]);
    }
    let out = cmd
        .arg(path)
        .env("TAUTO_TARGET_DIR", target)
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    String::from_utf8(out.stdout).unwrap()
}

