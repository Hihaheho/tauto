#[test]
fn native_build_rejects_corrupted_transition_proof() {
    let dir = std::env::temp_dir()
        .join(format!(
            "tauto-certified-state-invalid-{}",
            std::process::id()
        ))
        .join("certified-state");
    fs::create_dir_all(dir.join("src")).unwrap();
    let example = root().join("examples/certified-state");
    fs::copy(example.join("Tauto.eure"), dir.join("Tauto.eure")).unwrap();
    fs::copy(example.join("src/main.taut"), dir.join("src/main.taut")).unwrap();
    let source = fs::read_to_string(example.join("src/state.taut"))
        .unwrap()
        .replace("../../../std/", &format!("{}/std/", root().display()))
        .replace(
            "GateOpen(n) => GateOpen(Nat.pred(n))",
            "GateOpen(n) => GateOpen(succ(n))",
        );
    fs::write(dir.join("src/state.taut"), source).unwrap();
    let out = Command::new(env!("CARGO_BIN_EXE_tauto"))
        .args(["build", "--backend", "rust"])
        .arg(&dir)
        .env("TAUTO_TARGET_DIR", dir.join("build"))
        .output()
        .unwrap();
    assert!(!out.status.success());
    let diagnostic = format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(
        diagnostic.contains("gate_step_nonincreasing"),
        "{diagnostic}"
    );
    fs::remove_dir_all(dir).unwrap();
}

#[test]
fn adapter_corruption_is_a_runtime_regression_not_a_kernel_proof() {
    let dir = std::env::temp_dir()
        .join(format!(
            "tauto-state-adapter-invalid-{}",
            std::process::id()
        ))
        .join("certified-state");
    fs::create_dir_all(dir.join("src")).unwrap();
    let example = root().join("examples/certified-state");
    fs::copy(example.join("Tauto.eure"), dir.join("Tauto.eure")).unwrap();
    let state = fs::read_to_string(example.join("src/state.taut"))
        .unwrap()
        .replace("../../../std/", &format!("{}/std/", root().display()));
    fs::write(dir.join("src/state.taut"), state).unwrap();
    let main = fs::read_to_string(example.join("src/main.taut")).unwrap();
    assert_eq!(
        main.matches("cell := gate_advance(commands, cell)").count(),
        1
    );
    fs::write(
        dir.join("src/main.taut"),
        main.replace(
            "cell := gate_advance(commands, cell)",
            "cell := GateOpen(0)",
        ),
    )
    .unwrap();
    // The pure implementation's proof remains valid: it says nothing about a
    // caller which ignores the implementation and writes a different value.
    let proof = Command::new(env!("CARGO_BIN_EXE_tauto"))
        .arg("check")
        .arg(dir.join("src/state.taut"))
        .arg("--fresh")
        .output()
        .unwrap();
    assert!(proof.status.success());
    let output = run(&dir, false, &dir.join("build"));
    assert!(output.starts_with("denied = 0\n"));
    assert_ne!(
        output,
        "denied = 2\nremaining = 1\nrevoked = 1\nexhausted = 0\n"
    );
    fs::remove_dir_all(dir).unwrap();
}
